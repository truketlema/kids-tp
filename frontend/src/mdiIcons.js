const warnedIconNames = new Set()

const MdiSvgIcon = defineComponent({
  name: 'MdiSvgIcon',
  inheritAttrs: false,
  props: {
    tag: { type: [String, Object, Function], required: true },
    icon: { type: String, required: true },
  },
  setup(props, { attrs }) {
    return () => {
      const path = iconPaths[props.icon]

      if (!path && !warnedIconNames.has(props.icon)) {
        console.warn(`Unsupported MDI icon "${props.icon}".`)
        warnedIconNames.add(props.icon)
      }

      return h(props.tag, attrs, [
        h('svg', {
          class: 'v-icon__svg',
          xmlns: 'http://www.w3.org/2000/svg',
          viewBox: '0 0 24 24',
          role: 'img',
          'aria-hidden': 'true',
        }, [
          h('path', { d: path || mdiHelpCircleOutline }),
        ]),
      ])
    }
  },
})

export const mdiSvgIconSet = { component: MdiSvgIcon }
